-- Drop the database if it already exists so this script can be re-run safely
DROP DATABASE IF EXISTS ecommerce_analytics;

-- Create a fresh database with a sensible default character set / collation
CREATE DATABASE ecommerce_analytics
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE ecommerce_analytics;

-- -------------------------------------------------------------------------------------
-- Table: categories
-- Stores product categories (parent lookup table for products)
-- -------------------------------------------------------------------------------------
CREATE TABLE categories (
    category_id     INT AUTO_INCREMENT PRIMARY KEY,
    category_name   VARCHAR(100) NOT NULL UNIQUE,
    description     VARCHAR(255),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- -------------------------------------------------------------------------------------
-- Table: customers
-- Stores customer master data
-- -------------------------------------------------------------------------------------
CREATE TABLE customers (
    customer_id     INT AUTO_INCREMENT PRIMARY KEY,
    first_name      VARCHAR(50)  NOT NULL,
    last_name       VARCHAR(50)  NOT NULL,
    email           VARCHAR(150) NOT NULL UNIQUE,
    phone           VARCHAR(20),
    city            VARCHAR(100) NOT NULL,
    state           VARCHAR(100),
    country         VARCHAR(100) NOT NULL DEFAULT 'India',
    signup_date     DATE NOT NULL,
    customer_segment ENUM('Regular','Premium','VIP') NOT NULL DEFAULT 'Regular',
    CONSTRAINT chk_customers_email CHECK (email LIKE '%@%')
) ENGINE=InnoDB;

-- -------------------------------------------------------------------------------------
-- Table: products
-- Stores product catalog, each product belongs to one category (FK)
-- -------------------------------------------------------------------------------------
CREATE TABLE products (
    product_id      INT AUTO_INCREMENT PRIMARY KEY,
    product_name    VARCHAR(150) NOT NULL,
    category_id     INT NOT NULL,
    price           DECIMAL(10,2) NOT NULL,
    cost_price      DECIMAL(10,2) NOT NULL,
    stock_quantity  INT NOT NULL DEFAULT 0,
    brand           VARCHAR(100),
    is_active       TINYINT(1) NOT NULL DEFAULT 1,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id) REFERENCES categories(category_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_products_price CHECK (price > 0),
    CONSTRAINT chk_products_stock CHECK (stock_quantity >= 0)
) ENGINE=InnoDB;

-- -------------------------------------------------------------------------------------
-- Table: orders
-- Stores order header information, each order belongs to one customer (FK)
-- -------------------------------------------------------------------------------------
CREATE TABLE orders (
    order_id        INT AUTO_INCREMENT PRIMARY KEY,
    customer_id     INT NOT NULL,
    order_date      DATE NOT NULL,
    order_status    ENUM('Pending','Shipped','Delivered','Cancelled','Returned')
                        NOT NULL DEFAULT 'Delivered',
    shipping_city   VARCHAR(100),
    shipping_country VARCHAR(100) DEFAULT 'India',
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

-- -------------------------------------------------------------------------------------
-- Table: order_items
-- Line items for every order (many-to-many bridge between orders and products)
-- total_price is stored (denormalised) to make revenue queries realistic & fast,
-- exactly like most real-world OLTP schemas do.
-- -------------------------------------------------------------------------------------
CREATE TABLE order_items (
    order_item_id   INT AUTO_INCREMENT PRIMARY KEY,
    order_id        INT NOT NULL,
    product_id      INT NOT NULL,
    quantity        INT NOT NULL,
    unit_price      DECIMAL(10,2) NOT NULL,
    total_price     DECIMAL(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    CONSTRAINT fk_orderitems_order
        FOREIGN KEY (order_id) REFERENCES orders(order_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_orderitems_product
        FOREIGN KEY (product_id) REFERENCES products(product_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_orderitems_qty CHECK (quantity > 0)
) ENGINE=InnoDB;

-- -------------------------------------------------------------------------------------
-- Table: payments
-- One payment record per order (optional table, as requested)
-- -------------------------------------------------------------------------------------
CREATE TABLE payments (
    payment_id      INT AUTO_INCREMENT PRIMARY KEY,
    order_id        INT NOT NULL UNIQUE,
    payment_date    DATE NOT NULL,
    payment_method  ENUM('Credit Card','Debit Card','UPI','Net Banking','Cash on Delivery','Wallet')
                        NOT NULL,
    amount          DECIMAL(12,2) NOT NULL,
    payment_status  ENUM('Success','Failed','Refunded') NOT NULL DEFAULT 'Success',
    CONSTRAINT fk_payments_order
        FOREIGN KEY (order_id) REFERENCES orders(order_id)
        ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;


-- =====================================================================================
-- SECTION B: INDEXES (created here for foreign-key / commonly filtered columns)
-- Rationale for each index is explained in analysis_queries.sql Section "INDEXING"
-- =====================================================================================
CREATE INDEX idx_orders_customer_id   ON orders(customer_id);
CREATE INDEX idx_orders_order_date    ON orders(order_date);
CREATE INDEX idx_orderitems_order_id  ON order_items(order_id);
CREATE INDEX idx_orderitems_product_id ON order_items(product_id);
CREATE INDEX idx_products_category_id ON products(category_id);
CREATE INDEX idx_customers_city       ON customers(city);


